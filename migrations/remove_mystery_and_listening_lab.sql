-- =============================================================================
-- remove_mystery_and_listening_lab.sql  (2026-11-14)
-- =============================================================================
-- Purpose: delete the last database remnants of two retired features. Their
-- tables, RPCs and prompt templates were dropped by
-- archive_unused_modules_2026_09_21.sql, which deliberately kept:
--   * the dim_test_types rows 'mystery' and 'listening_lab'
--   * test_skill_ratings rows created for those two types on every test
--   * questions.pool_source ('original' | 'lab_expansion') with its CHECK
--     constraint and the index idx_questions_test_pool
-- Nothing in the application reads any of them.
--
-- Live state checked 2026-11-14 (read-only):
--   dim_test_types: id 8 'mystery', id 12 'listening_lab'
--   test_skill_ratings: 308 rows for those two types
--   test_attempts, user_skill_ratings, user_skill_rating_adjustments: 0 rows
--   questions.pool_source: 'original' on every row; no function or view reads it
--
-- Safety: the guard refuses to run if any learner attempt or learner rating
-- references either type, so no learner history can be deleted by this file.
--
-- After applying: restart the web app and any running test-generation job.
-- They cache the active test types and would otherwise try to create rating
-- rows for the two deleted types on the next generated test.
--
-- Idempotent and re-runnable. REQUIRES USER APPROVAL TO APPLY LIVE.
--
-- Rollback (the rating rows are regenerated by scripts/backfill_test_skill_ratings.py):
--   INSERT INTO public.dim_test_types (id, type_code, ...) VALUES (8, 'mystery', ...), (12, 'listening_lab', ...);
--   ALTER TABLE public.questions ADD COLUMN pool_source text NOT NULL DEFAULT 'original'
--     CONSTRAINT chk_questions_pool_source CHECK (pool_source IN ('original', 'lab_expansion'));
--   CREATE INDEX idx_questions_test_pool ON public.questions (test_id, pool_source);
--   Save the two dim_test_types rows first if a rollback may be wanted:
--     SELECT * FROM public.dim_test_types WHERE type_code IN ('mystery', 'listening_lab');
-- =============================================================================

BEGIN;

DO $$
DECLARE
  v_ids smallint[];
  v_n   bigint;
BEGIN
  SELECT array_agg(id) INTO v_ids
    FROM public.dim_test_types
   WHERE type_code IN ('mystery', 'listening_lab');

  IF v_ids IS NOT NULL THEN
    SELECT (SELECT count(*) FROM public.test_attempts                 WHERE test_type_id = ANY (v_ids))
         + (SELECT count(*) FROM public.user_skill_ratings            WHERE test_type_id = ANY (v_ids))
         + (SELECT count(*) FROM public.user_skill_rating_adjustments WHERE test_type_id = ANY (v_ids))
      INTO v_n;
    IF v_n > 0 THEN
      RAISE EXCEPTION 'learner rows reference the mystery / listening_lab test types (% rows); not deleting', v_n;
    END IF;

    DELETE FROM public.test_skill_ratings WHERE test_type_id = ANY (v_ids);
    DELETE FROM public.dim_test_types     WHERE id = ANY (v_ids);
  END IF;

  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'questions'
                AND column_name = 'pool_source') THEN
    EXECUTE 'SELECT count(*) FROM public.questions WHERE pool_source IS DISTINCT FROM ''original''' INTO v_n;
    IF v_n > 0 THEN
      RAISE EXCEPTION '% questions have a pool_source other than original; not dropping the column', v_n;
    END IF;
  END IF;
END $$;

DROP INDEX IF EXISTS public.idx_questions_test_pool;
ALTER TABLE public.questions DROP CONSTRAINT IF EXISTS chk_questions_pool_source;
ALTER TABLE public.questions DROP COLUMN IF EXISTS pool_source;

DELETE FROM public.prompt_templates
 WHERE task_name IN ('mystery_clue', 'mystery_deduction', 'mystery_plot', 'mystery_question', 'mystery_scene');

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.dim_test_types WHERE type_code IN ('mystery', 'listening_lab')) THEN
    RAISE EXCEPTION 'mystery / listening_lab test types still present';
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'questions' AND column_name = 'pool_source') THEN
    RAISE EXCEPTION 'questions.pool_source still present';
  END IF;
END $$;

COMMIT;
