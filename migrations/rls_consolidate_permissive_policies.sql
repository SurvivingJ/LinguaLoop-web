-- Consolidate overlapping permissive RLS policies (TASK-932, 2026-11-11).
--
-- ORDER: apply ONLY AFTER the security-hardening migrations (TASK-875/876/877/
-- 879/880/882). They drop policies BY NAME; merging first would hide those
-- policies inside merged ones and silently defeat the drops. Guard 0 enforces
-- this.
--
-- WHAT IT DOES. For every public table where one role has more than one
-- permissive policy for the same command (Supabase advisor 0006), all of the
-- table's policies are replaced by one policy per command:
--     SELECT  USING      = OR of the USING of every SELECT/ALL policy
--     INSERT  WITH CHECK = OR of (WITH CHECK, else USING) of every INSERT/ALL policy
--     UPDATE  USING      = OR of the USING of every UPDATE/ALL policy
--             WITH CHECK = OR of (WITH CHECK, else USING) of every UPDATE/ALL policy
--     DELETE  USING      = OR of the USING of every DELETE/ALL policy
-- That is exactly how Postgres already combines permissive policies, so access
-- does not change. Tables are skipped (left untouched) when they have a
-- RESTRICTIVE policy, policies with different role lists for one command, or a
-- SELECT/UPDATE/DELETE/ALL policy without USING.
--
-- SELF-VERIFYING. Before and after the rewrite it records, for a set of real
-- personas (anon, several signed-in users, the admin), what each can SELECT
-- (row count + hash of every visible row) and lock FOR UPDATE (UPDATE policies'
-- USING) on every affected table, plus the error code when access is denied.
-- Any difference raises, which rolls the whole migration back: either it
-- applies with identical access or nothing changes. INSERT/UPDATE WITH CHECK and
-- DELETE cannot be probed without writing rows; they are equal by construction
-- (the same expressions, OR'ed).
--
-- Idempotent: a re-run finds no overlapping policies and does nothing.
-- Rollback: migrations/rls_consolidate_permissive_policies_rollback.sql is
-- generated by the preview query at the bottom of this file BEFORE applying.

DO $$
DECLARE
    v_tbl      text;
    v_cmd      text;
    pol        record;
    roles_txt  text;
    roleset    text[];
    using_terms text[];
    check_terms text[];
    skip_reason text;
    targets    text[] := '{}';
    persona    record;
    v_count    bigint;
    v_hash     text;
    v_state    text;
    stmt       text;
    n_before   int;
    n_after    int;
    mismatches int;
BEGIN
    -- 0. Ordering guard: policies the security migrations drop must be gone.
    IF EXISTS (
        SELECT 1 FROM pg_policies
         WHERE schemaname = 'public'
           AND (tablename, policyname) IN (
                ('user_reports', 'Admin can view all reports'),
                ('users', 'users_admin_all'),
                ('user_tokens', 'tokens_own_data'))
    ) THEN
        RAISE EXCEPTION 'Apply the security-hardening migrations (TASK-875 and friends) before consolidating RLS policies';
    END IF;

    -- 1. Target tables: some (role, command) has more than one permissive policy.
    SELECT coalesce(array_agg(DISTINCT t), '{}') INTO targets
      FROM (
        SELECT p.tablename AS t, r.role, c.cmd
          FROM pg_policies p
          CROSS JOIN LATERAL unnest(p.roles) AS r(role)
          CROSS JOIN LATERAL unnest(CASE WHEN p.cmd = 'ALL'
                                         THEN ARRAY['SELECT','INSERT','UPDATE','DELETE']
                                         ELSE ARRAY[p.cmd] END) AS c(cmd)
         WHERE p.schemaname = 'public' AND p.permissive = 'PERMISSIVE'
         GROUP BY 1, 2, 3
        HAVING count(*) > 1
      ) x;

    IF cardinality(targets) = 0 THEN
        RAISE NOTICE 'No overlapping permissive policies: nothing to do.';
        RETURN;
    END IF;

    -- 2. Personas: anon, up to 4 non-admin users with the most data, the admins.
    CREATE TEMP TABLE _rls_personas ON COMMIT DROP AS
    SELECT 'anon'::text AS label, 'anon'::text AS role, '{"role":"anon"}'::text AS claims
    UNION ALL
    SELECT 'user:' || u.id, 'authenticated',
           json_build_object('sub', u.id, 'role', 'authenticated')::text
      FROM (SELECT u.id FROM public.users u
             LEFT JOIN public.dim_subscription_tiers t ON t.id = u.subscription_tier_id
             WHERE coalesce(t.is_admin, false) = false
             ORDER BY (SELECT count(*) FROM public.test_attempts a WHERE a.user_id = u.id) DESC, u.id
             LIMIT 4) u
    UNION ALL
    SELECT 'admin:' || u.id, 'authenticated',
           json_build_object('sub', u.id, 'role', 'authenticated')::text
      FROM public.users u JOIN public.dim_subscription_tiers t ON t.id = u.subscription_tier_id
     WHERE t.is_admin;

    CREATE TEMP TABLE _rls_probe (phase text, label text, tbl text, kind text,
                                  n bigint, hash text, state text) ON COMMIT DROP;

    -- 3. Probe (before), rewrite, probe (after).
    FOR n_before IN 1..2 LOOP
        FOR persona IN SELECT * FROM _rls_personas LOOP
            FOREACH v_tbl IN ARRAY targets LOOP
                -- SELECT visibility
                BEGIN
                    PERFORM set_config('request.jwt.claims', persona.claims, true);
                    PERFORM set_config('request.jwt.claim.sub', coalesce(persona.claims::json->>'sub', ''), true);
                    PERFORM set_config('request.jwt.claim.role', persona.claims::json->>'role', true);
                    EXECUTE format('SET LOCAL ROLE %I', persona.role);
                    EXECUTE format('SELECT count(*), md5(coalesce(string_agg(t::text, %L ORDER BY t::text), %L)) FROM public.%I t',
                                   E'\n', '', v_tbl) INTO v_count, v_hash;
                    v_state := 'ok';
                    RESET ROLE;
                EXCEPTION WHEN OTHERS THEN
                    v_count := NULL; v_hash := NULL; v_state := SQLSTATE;
                    RESET ROLE;
                END;
                INSERT INTO _rls_probe VALUES (CASE n_before WHEN 1 THEN 'before' ELSE 'after' END,
                                               persona.label, v_tbl, 'select', v_count, v_hash, v_state);
                -- UPDATE policies' USING, without writing: SELECT ... FOR UPDATE
                BEGIN
                    PERFORM set_config('request.jwt.claims', persona.claims, true);
                    PERFORM set_config('request.jwt.claim.sub', coalesce(persona.claims::json->>'sub', ''), true);
                    PERFORM set_config('request.jwt.claim.role', persona.claims::json->>'role', true);
                    EXECUTE format('SET LOCAL ROLE %I', persona.role);
                    EXECUTE format('SELECT count(*) FROM (SELECT 1 FROM public.%I FOR UPDATE) s', v_tbl) INTO v_count;
                    v_state := 'ok';
                    RESET ROLE;
                EXCEPTION WHEN OTHERS THEN
                    v_count := NULL; v_state := SQLSTATE;
                    RESET ROLE;
                END;
                INSERT INTO _rls_probe VALUES (CASE n_before WHEN 1 THEN 'before' ELSE 'after' END,
                                               persona.label, v_tbl, 'for_update', v_count, NULL, v_state);
            END LOOP;
        END LOOP;
        PERFORM set_config('request.jwt.claims', '', true);
        PERFORM set_config('request.jwt.claim.sub', '', true);
        PERFORM set_config('request.jwt.claim.role', '', true);

        EXIT WHEN n_before = 2;

        -- Rewrite each target table.
        FOREACH v_tbl IN ARRAY targets LOOP
            skip_reason := NULL;
            IF EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = v_tbl
                       AND permissive <> 'PERMISSIVE') THEN
                skip_reason := 'has a RESTRICTIVE policy';
            ELSIF EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = v_tbl
                          AND cmd IN ('SELECT','UPDATE','DELETE','ALL') AND qual IS NULL) THEN
                skip_reason := 'has a policy without USING';
            END IF;
            -- one role list per command
            IF skip_reason IS NULL THEN
                FOREACH v_cmd IN ARRAY ARRAY['SELECT','INSERT','UPDATE','DELETE'] LOOP
                    IF (SELECT count(DISTINCT roles) FROM pg_policies
                         WHERE schemaname = 'public' AND tablename = v_tbl AND cmd IN (v_cmd, 'ALL')) > 1 THEN
                        skip_reason := 'different role lists for ' || v_cmd;
                    END IF;
                END LOOP;
            END IF;
            IF skip_reason IS NOT NULL THEN
                RAISE NOTICE 'skip %: %', v_tbl, skip_reason;
                CONTINUE;
            END IF;

            -- Build the merged policies before dropping anything.
            CREATE TEMP TABLE IF NOT EXISTS _rls_new (tbl text, stmt text) ON COMMIT DROP;
            FOREACH v_cmd IN ARRAY ARRAY['SELECT','INSERT','UPDATE','DELETE'] LOOP
                SELECT array_agg(DISTINCT '(' || p.qual || ')') FILTER (WHERE p.qual IS NOT NULL AND v_cmd <> 'INSERT'),
                       array_agg(DISTINCT '(' || coalesce(p.with_check, p.qual) || ')') FILTER (WHERE v_cmd IN ('INSERT','UPDATE')),
                       min(array_to_string(p.roles, ','))
                  INTO using_terms, check_terms, roles_txt
                  FROM pg_policies p
                 WHERE p.schemaname = 'public' AND p.tablename = v_tbl AND p.cmd IN (v_cmd, 'ALL');
                IF roles_txt IS NULL THEN CONTINUE; END IF;   -- no policy for this command: stays denied
                roleset := string_to_array(roles_txt, ',');
                stmt := format('CREATE POLICY %I ON public.%I AS PERMISSIVE FOR %s TO %s',
                               'rls_' || lower(v_cmd), v_tbl, v_cmd,
                               (SELECT string_agg(CASE WHEN r = 'public' THEN 'public' ELSE quote_ident(r) END, ', ')
                                  FROM unnest(roleset) r));
                IF v_cmd <> 'INSERT' THEN
                    stmt := stmt || ' USING (' || array_to_string(using_terms, ' OR ') || ')';
                END IF;
                IF v_cmd IN ('INSERT','UPDATE') THEN
                    stmt := stmt || ' WITH CHECK (' || array_to_string(check_terms, ' OR ') || ')';
                END IF;
                INSERT INTO _rls_new VALUES (v_tbl, stmt);
            END LOOP;

            FOR pol IN SELECT policyname FROM pg_policies WHERE schemaname = 'public' AND tablename = v_tbl LOOP
                EXECUTE format('DROP POLICY %I ON public.%I', pol.policyname, v_tbl);
            END LOOP;
            FOR stmt IN SELECT n.stmt FROM _rls_new n WHERE n.tbl = v_tbl LOOP
                EXECUTE stmt;
            END LOOP;
            DELETE FROM _rls_new WHERE _rls_new.tbl = v_tbl;
        END LOOP;
    END LOOP;

    -- 4. Compare.
    SELECT count(*) INTO mismatches
      FROM _rls_probe b
      JOIN _rls_probe a ON a.phase = 'after' AND a.label = b.label AND a.tbl = b.tbl AND a.kind = b.kind
     WHERE b.phase = 'before'
       AND (a.n IS DISTINCT FROM b.n OR a.hash IS DISTINCT FROM b.hash OR a.state IS DISTINCT FROM b.state);
    IF mismatches > 0 THEN
        RAISE EXCEPTION 'RLS consolidation changed access in % probe(s); nothing applied. First: %', mismatches,
            (SELECT format('%s / %s / %s: before n=%s state=%s, after n=%s state=%s', b.label, b.tbl, b.kind, b.n, b.state, a.n, a.state)
               FROM _rls_probe b JOIN _rls_probe a ON a.phase = 'after' AND a.label = b.label AND a.tbl = b.tbl AND a.kind = b.kind
              WHERE b.phase = 'before'
                AND (a.n IS DISTINCT FROM b.n OR a.hash IS DISTINCT FROM b.hash OR a.state IS DISTINCT FROM b.state)
              LIMIT 1);
    END IF;

    SELECT count(*) INTO n_after FROM _rls_probe WHERE phase = 'after';
    RAISE NOTICE 'Consolidated % table(s); % probes identical before and after.', cardinality(targets), n_after;
END $$;

