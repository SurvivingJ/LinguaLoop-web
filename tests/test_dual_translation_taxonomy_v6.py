            assert len(re.findall(r"[ぁ-ゖ]", d["ja"])) >= 2, (kind, st, "ja")
            assert len(re.findall(r"[A-Za-z]{3,}", d["en"])) >= 4, (kind, st, "en")
            assert re.search(r"[一-鿿]", d["zh"]), (kind, st, "zh")
            if kind == "templates":
                assert "“{learner_form}”" in d["en"] or "“{corrected_form}”" in d["en"], (st, "en")
                assert "「{learner_form}」" in d["ja"] or "「{corrected_form}」" in d["ja"], (st, "ja")
                assert "“{learner_form}”" in d["zh"] or "“{corrected_form}”" in d["zh"], (st, "zh")


