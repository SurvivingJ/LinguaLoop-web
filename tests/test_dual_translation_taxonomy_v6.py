def test_subtype_meta_total_over_every_pair_slug(tax, pair_slugs):
    meta = tax["subtype_meta"]
    for st in pair_slugs:
        assert st in meta, f"{st} missing from subtype_meta"
        m = meta[st]
        assert m["dimension"] in DIMENSIONS, st
        assert m["default_severity"] in SEVERITIES, st
        assert isinstance(m["treatable"], bool) and isinstance(m["cloze_suitable"], bool), st
        assert m["class"] in {"G", "S", "R", "D", "F"}, st
        buckets = m["jev_bucket"]
        values = buckets.values() if isinstance(buckets, dict) else [buckets]
        assert all(b in JEV_BUCKETS for b in values), (st, buckets)
        assert "historical_alias" not in m, f"live v6 slug {st} marked historical"
        assert "definition" not in m, "definition is not copied into subtype_meta"
    assert len(pair_slugs) == 40


def test_subtype_meta_values_match_merged_taxonomy(tax, merged):
    meta = tax["subtype_meta"]
