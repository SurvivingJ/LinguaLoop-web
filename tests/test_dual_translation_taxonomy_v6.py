def _sql_statements_only() -> str:
    sql = V6_PATH.read_text(encoding="utf-8")
    sql = re.sub(r"\$taxonomy\$.*?\$taxonomy\$", "$taxonomy$$taxonomy$", sql, flags=re.DOTALL)
    return "\n".join(line for line in sql.splitlines() if not line.lstrip().startswith("--"))


def test_seed_inserts_v6_inactive():
    sql = _sql_statements_only()
    assert re.search(r"VALUES \(\s*6,\s*false,", sql)
    assert "ON CONFLICT (version) DO UPDATE" in sql


def test_seed_never_activates_and_never_updates_other_rows():
    sql = _sql_statements_only()
    assert not re.search(r"is_active\s*=\s*true", sql, re.IGNORECASE)
    assert not re.search(r"\bUPDATE\s+public\.", sql, re.IGNORECASE)
    assert not re.search(r"\bDELETE\b", sql, re.IGNORECASE)
    do_update = sql.split("ON CONFLICT (version) DO UPDATE", 1)[1].split(";", 1)[0]
    assert "is_active" not in do_update
    assert set(re.findall(r"(\w+)\s*=\s*EXCLUDED", do_update)) == {"taxonomy", "description"}


