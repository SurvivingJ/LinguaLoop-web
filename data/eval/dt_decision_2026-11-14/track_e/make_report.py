# ---- ensemble: second opinion (sentence flagged by BOTH LLMs) from the frozen runs, no extra calls
def sent_flags(alias):
    run = {}
    with open(os.path.join(E.HERE, "runs", f"{alias}__p1_expl.jsonl"), encoding="utf-8") as f:
        for r in map(json.loads, f): run[r["id"]] = r
    out_ = {}
    for it in AN.items:
        pbs = collections.defaultdict(list)
        for p in run[it["id"]]["errors"]:
            pbs[AN.sent_index(it, p["span"][0])].append(p)
        out_[it["id"]] = {s["i"]: (s["cat"], s["flag"]) for s in AN.sentence_table(it, pbs)}
    return out_
