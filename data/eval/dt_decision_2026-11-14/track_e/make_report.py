def f2(x):
    return "—" if x is None else (f"{x:.2f}".replace("0.", ".", 1) if abs(x) < 1 else f"{x:.2f}")


def pooled(gr, lv):
    tp = fp = fn = 0; ci = collections.Counter(); sc = collections.defaultdict(collections.Counter)
    tt = tn = 0; q = []; ex = collections.defaultdict(list); usd = []; lat = []; n = 0; loc = collections.defaultdict(collections.Counter)
    for lang in E.LANGS:
        v = gr.get(f"{lang}/{lv}")
        if not v:
            continue
        n += v["n"]
        a, b, c = v["tp_fp_fn"]; tp += a; fp += b; fn += c
        for k, x in v["clean_items"].items(): ci[k] += x
        for cat, d in v["sentences"].items():
            for k, x in d.items(): sc[cat][k] += x
        if v["type_top1"] is not None:
            tt += v["type_top1"] * a; tn += a
        for d in AN.DIMS:
            if v["qwk_" + d] is not None: q.append(v["qwk_" + d])
            ex[d].append(v["exact_" + d] * v["n"])
        ex["3"].append(v["exact_3dim"] * v["n"])
        usd.append(v["usd_per_item"] * v["n"]); lat.append(v["p50_latency_s"])
        for k, d in (v.get("gold_error_location") or {}).items():
            for kk, x in d.items(): loc[k][kk] += x
    return {"n_items": n, "precision": round(tp / (tp + fp), 3) if tp + fp else None, "recall": round(tp / (tp + fn), 3) if tp + fn else None,
            "tp_fp_fn": [tp, fp, fn], "type_top1": round(tt / tn, 3) if tn else None, "clean_items": dict(ci),
            "sentences": {k: dict(v) for k, v in sc.items()}, "mean_qwk_9cells": round(statistics.mean(q), 3) if q else None,
            "exact": {d: round(sum(x) / n, 3) for d, x in ex.items()}, "usd_per_item": round(sum(usd) / n, 6),
            "p50_latency_s_mean_of_langs": round(statistics.mean(lat), 2), "gold_error_location": {k: dict(v) for k, v in loc.items()}}


