#!/usr/bin/env python3
"""Write the browser's copy of the language registry.

    python scripts/build_language_registry_js.py           # writes static/js/language-registry.js
    python scripts/build_language_registry_js.py --check   # exit 1 when the file is out of date

The source is services/language_registry.py. Run this after changing it;
tests/test_language_registry.py fails while the file is stale.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from services import language_registry  # noqa: E402

OUT = os.path.join(ROOT, 'static', 'js', 'language-registry.js')

TEMPLATE = """// GENERATED by scripts/build_language_registry_js.py from services/language_registry.py.
// Do not edit: change the Python registry and run the script.
(function (root) {
  'use strict';

  const DATA = __DATA__;

  const all = DATA.languages;
  const byId = {};
  const byCode = {};
  all.forEach(function (lang) {
    byId[lang.id] = lang;
    byCode[lang.code] = lang;
    lang.legacyCodes.forEach(function (code) {
      byCode[code] = lang;
    });
  });

  // An id (number or digit string), a code (current or legacy, any case) or a language object.
  function find(ref, includePlanned) {
    let lang = null;
    if (ref && typeof ref === 'object') lang = byId[ref.id] || null;
    else if (typeof ref === 'number') lang = byId[ref] || null;
    else if (typeof ref === 'string') {
      const key = ref.trim().toLowerCase();
      lang = byCode[key] || (/^\\d+$/.test(key) ? byId[Number(key)] : null) || null;
    }
    if (!lang || (!lang.active && !includePlanned)) return null;
    return lang;
  }

  function list(includePlanned) {
    return all.filter(function (lang) {
      return includePlanned || lang.active;
    });
  }

  function idToCode(includePlanned) {
    const out = {};
    list(includePlanned).forEach(function (lang) {
      out[lang.id] = lang.code;
    });
    return out;
  }

  function codeToId(includePlanned, legacy) {
    const out = {};
    list(includePlanned).forEach(function (lang) {
      out[lang.code] = lang.id;
      if (legacy) {
        lang.legacyCodes.forEach(function (code) {
          out[code] = lang.id;
        });
      }
    });
    return out;
  }

  function codeOf(ref, fallback) {
    const lang = find(ref);
    return lang ? lang.code : fallback === undefined ? '' : fallback;
  }

  function idOf(ref, fallback) {
    const lang = find(ref);
    return lang ? lang.id : fallback === undefined ? null : fallback;
  }

  function hasFeature(ref, feature) {
    const lang = find(ref, true);
    return !!lang && lang.features.indexOf(feature) !== -1;
  }

  function isCjk(ref) {
    const lang = find(ref, true);
    return !!lang && lang.script === 'cjk';
  }

  function flagOf(ref, fallback) {
    const lang = find(ref, true);
    return lang ? lang.flag : fallback === undefined ? '\\u{1F310}' : fallback;
  }

  const api = {
    list: list,
    find: find,
    idToCode: idToCode,
    codeToId: codeToId,
    codeOf: codeOf,
    idOf: idOf,
    hasFeature: hasFeature,
    isCjk: isCjk,
    flagOf: flagOf,
  };

  root.LinguaLanguages = api;
})(typeof window !== 'undefined' ? window : globalThis);
"""


def render():
    data = json.dumps(language_registry.browser_payload(), ensure_ascii=False, indent=2)
    data = data.replace('\n', '\n  ')
    return TEMPLATE.replace('__DATA__', data)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    body = render()
    if '--check' in argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != body:
            print('static/js/language-registry.js is out of date: run scripts/build_language_registry_js.py')
            return 1
        print('static/js/language-registry.js is up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(body)
    print(f'wrote {os.path.relpath(OUT, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
