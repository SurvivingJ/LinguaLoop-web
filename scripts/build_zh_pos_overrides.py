"""Build data/lexicon/zh_pos_overrides.tsv: our part-of-speech labels that
correct jieba's dictionary tags (2026-11-12).

jieba tags words from its own dictionary, which has errors (宗教改革 and 高昂
"nr" = person name, 吸管 "v"). When dim_vocabulary holds a trusted label for a
Chinese word -- one not written by jieba itself (the sense generator's label,
an authoring-pipeline label, a Chinese grammar label such as 形容词) -- and
its class differs from jieba's dictionary tag, the word (two or more
characters; single characters change part of speech with context) goes in
the file with
the jieba tag for our class. services/vocabulary/zh_segmenter.py applies it
after splitting, so splitting is unchanged and only the tag moves.

Read-only against the database. Re-run after labels change:
    python scripts/build_zh_pos_overrides.py [--dry-run]
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import requests  # noqa: E402

from services.vocabulary.pos import CANONICAL_POS, normalize_pos  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   'data', 'lexicon', 'zh_pos_overrides.tsv')

# Our standard label -> the jieba (ICTCLAS) tag that carries it.
JIEBA_TAG = {
    'noun': 'n', 'verb': 'v', 'adjective': 'a', 'adverb': 'd', 'pronoun': 'r',
    'preposition': 'p', 'conjunction': 'c', 'particle': 'u', 'measure_word': 'q',
    'idiom': 'i', 'phrase': 'l', 'numeral': 'm', 'interjection': 'e',
    'auxiliary': 'v', 'adnominal': 'b', 'determiner': 'r',
}
# Labels jieba never writes: the sense generator's names and Chinese grammar labels.
_TRUSTED = set(CANONICAL_POS) | {'名词', '动词', '形容词', '副词', '代词', '介词', '连词',
                                 '助词', '量词', '数词', '叹词', '成语', '情态动词'}


def trusted_label(row: dict):
    """The row's label if it did not come from jieba, else None."""
    label = (row.get('part_of_speech') or '').strip()
    raw = (row.get('part_of_speech_raw') or '').strip()
    if raw:  # after standardise_part_of_speech.sql: raw = the tagger's original
        if normalize_pos(raw) == label:
            return None  # label is just jieba's tag, standardised
        if raw not in _TRUSTED:
            return label if label in CANONICAL_POS else None
    return normalize_pos(label) if label in _TRUSTED else None


def fetch_rows() -> list:
    base = os.environ['SUPABASE_URL'].rstrip('/')
    key = os.environ['SUPABASE_SERVICE_ROLE_KEY']
    headers = {'apikey': key, 'Authorization': f'Bearer {key}'}
    rows, start = [], 0
    while True:
        resp = requests.get(f'{base}/rest/v1/dim_vocabulary',
                            params={'select': '*', 'language_id': 'eq.1', 'order': 'id'},
                            headers={**headers, 'Range': f'{start}-{start + 999}'}, timeout=60)
        resp.raise_for_status()
        rows += resp.json()
        if len(resp.json()) < 1000:
            return rows
        start += 1000


def build(rows: list) -> list:
    import jieba
    import jieba.posseg as pseg
    jieba.initialize()
    tags = pseg.dt.word_tag_tab
    out = {}
    for r in rows:
        word = (r.get('lemma') or '').strip()
        ours = trusted_label(r)
        theirs = tags.get(word)
        # Single characters change part of speech with context (给 preposition /
        # verb, 箱 noun / measure word): a word-level override would be wrong
        # half the time, so only words of two or more characters are corrected.
        if len(word) < 2 or not ours or ours == 'other' or theirs is None or ours not in JIEBA_TAG:
            continue
        if normalize_pos(theirs) != ours:
            out[word] = (JIEBA_TAG[ours], theirs, ours)
    return sorted((w, t, theirs, ours) for w, (t, theirs, ours) in out.items())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args()
    overrides = build(fetch_rows())
    print(f'{len(overrides)} overrides')
    for w, t, theirs, ours in overrides[:25]:
        print(f'  {w}\t{theirs} -> {t} ({ours})')
    if not args.dry_run:
        with open(OUT, 'w', encoding='utf-8') as fh:
            fh.write('# word<TAB>jieba tag to use<TAB>jieba dictionary tag<TAB>our label\n')
            fh.write('# Generated by scripts/build_zh_pos_overrides.py from dim_vocabulary.\n')
            for row in overrides:
                fh.write('\t'.join(row) + '\n')
        print('wrote', OUT)


if __name__ == '__main__':
    main()
